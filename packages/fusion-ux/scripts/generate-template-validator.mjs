import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(packageDirectory, 'src/validation/schemas.ts');
const outputPath = resolve(packageDirectory, 'src/validation/fragmentTemplate.validator.generated.js');
const declarationPath = resolve(packageDirectory, 'src/validation/fragmentTemplate.validator.generated.d.ts');
const libValidationDirectory = resolve(packageDirectory, 'lib/validation');
const checkOnly = process.argv.includes('--check');
const copyToLib = process.argv.includes('--copy-to-lib');

if (copyToLib) {
    await mkdir(libValidationDirectory, { recursive: true });
    await Promise.all([
        readFile(outputPath).then((source) =>
            writeFile(resolve(libValidationDirectory, 'fragmentTemplate.validator.generated.js'), source),
        ),
        readFile(declarationPath).then((declaration) =>
            writeFile(resolve(libValidationDirectory, 'fragmentTemplate.validator.generated.d.ts'), declaration),
        ),
    ]);
} else {
    const [{ default: Ajv }, { default: standaloneCode }, { FragmentTemplateSchema }] = await Promise.all([
        import('ajv'),
        import('ajv/dist/standalone/index.js'),
        import(pathToFileURL(schemaPath).href),
    ]);
    const ajv = new Ajv({
        allErrors: true,
        verbose: true,
        code: { esm: true, source: true },
    });
    const validate = ajv.compile(FragmentTemplateSchema);
    const unformattedSource = [
        '// Generated by scripts/generate-template-validator.mjs. Do not edit.',
        '// biome-ignore-all lint: Generated AJV standalone validator.',
        standaloneCode(ajv, validate),
        '',
    ].join('\n');
    const generatedSource = execFileSync('pnpm', ['exec', 'biome', 'format', `--stdin-file-path=${outputPath}`], {
        cwd: packageDirectory,
        encoding: 'utf8',
        input: unformattedSource,
    });

    if (checkOnly) {
        const currentSource = await readFile(outputPath, 'utf8').catch(() => '');
        if (currentSource !== generatedSource) {
            throw new Error('Generated template validator is stale. Run `pnpm run generate:validator`.');
        }
    } else {
        await writeFile(outputPath, generatedSource);
    }
}
