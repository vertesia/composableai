describe('the TypeScript type says what the schema says', () => {
    it('widens page ranges to number[][], which is what the component has always described', () => {
        // `[number, number][]` is what the interface used to claim. The published component is
        // `items: {type: integer}` with `minItems`/`maxItems` — a two-element ARRAY, not a tuple —
        // because a Zod tuple emits `prefixItems`, which generated Java and Go clients read
        // differently. The wire shape is unchanged; the SDK type is corrected to match it.
        assertType<Equals<IntakePageRanges, number[][]>>(true);
        expect(validate({ extraction: { page_ranges: [[1, 2]] } }), errors()).toBe(true);
    });

    it('keeps the two type refs’ default_view in step with the policy', () => {
        // Those refs spell the union out rather than writing `ContentTypeIntakePolicy['default_view']`,
        // because indexing into a canonical alias makes the generator DROP the property instead of
        // failing. This is what stops the restatement from drifting.
        assertType<
            Equals<
                NonNullable<ContentObjectTypeRef['default_view']>,
                NonNullable<ContentTypeIntakePolicy['default_view']>
            >
        >(true);
    });
});

