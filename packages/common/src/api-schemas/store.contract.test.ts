describe('runtime tightenings — recorded as operation 25 of the 1.5 runbook', () => {
    it('rejects an explicit null where the hand-written schema accepted one', () => {
        // The replaced schema carried `nullable: true` on 112 subschemas and AJV honours that keyword
        // for OpenAPI compatibility, so 101 of them accepted `null` — which neither the TypeScript
        // type nor the published component has ever allowed. The fields are optional, not nullable.
        expect(validate({ generate_toc: null })).toBe(false);
        expect(validate({ rendering_template: null })).toBe(false);
        expect(validate({ extraction: { max_pages: null } })).toBe(false);
        expect(validate({ extraction: null })).toBe(false);
        // Omission is still how you say "inherit", which is what every one of those fields meant.
        expect(validate({}), errors()).toBe(true);
        expect(validate({ extraction: {} }), errors()).toBe(true);
    });

    it('closes the execution config, which the published component already described closed', () => {
        // `config` was `additionalProperties: true` in the hand-written schema while
        // `InteractionExecutionConfiguration` has always been published closed. A stored policy
        // carrying an undeclared key there is now rejected at write time.
        expect(ApiSchemaComponents.InteractionExecutionConfiguration.additionalProperties).toBe(false);
        expect(validate({ extraction: { config: { model: 'claude-sonnet-4-5' } } }), errors()).toBe(true);
        expect(
            validate({ extraction: { config: { prompt_cache_mode: 'required', prompt_cache_ttl_seconds: 3600 } } }),
            errors(),
        ).toBe(true);
        expect(validate({ extraction: { config: { prompt_cache_ttl_seconds: 59 } } })).toBe(false);
        expect(validate({ extraction: { config: { temperature: 0.5 } } })).toBe(false);
        expect(validate({ extraction: { config: { http_timeout: { socketTimeout: 1000 } } } })).toBe(false);
    });

    it('validates model_options against the union instead of accepting any object', () => {
        // Same class: `model_options` was `{type: object, additionalProperties: true}` in the
        // hand-written schema and `$ref: ModelOptions` in the published component. It now has to name
        // a driver through `_option_id`, which is the discriminator generated clients already use.
        expect(ApiSchemaComponents.ContentTypeIntakePolicy).toBeDefined();
        expect(
            validate({
                extraction: { config: { model_options: { _option_id: 'openai-text', temperature: 0.5 } } },
            }),
            errors(),
        ).toBe(true);
        expect(validate({ extraction: { config: { model_options: { temperature: 0.5 } } } })).toBe(false);
        expect(validate({ extraction: { config: { model_options: { _option_id: 'not-a-driver' } } } })).toBe(false);
        // The empty object is rejected for the same reason, which is why nothing may PUT it on the
        // wire — see `normalizeModelOptions`, which drops an options bag with no options in it.
        expect(validate({ extraction: { config: { model_options: {} } } })).toBe(false);
    });

    it('constrains the two config enums that were unconstrained strings', () => {
        expect(validate({ extraction: { config: { run_data: 'STANDARD' } } }), errors()).toBe(true);
        expect(validate({ extraction: { config: { run_data: 'WHATEVER' } } })).toBe(false);
        expect(validate({ extraction: { config: { configMode: 'RUN_CONFIG_ONLY' } } }), errors()).toBe(true);
        expect(validate({ extraction: { config: { configMode: 'WHATEVER' } } })).toBe(false);
    });
});

describe('the five content-type shapes are composed, not repeated', () => {
    const properties = (name: string) =>
        Object.keys((ApiSchemaComponents[name] as { properties: Record<string, unknown> }).properties);
    const property = (name: string, key: string) =>
        (ApiSchemaComponents[name] as { properties: Record<string, JsonObject> }).properties[key];

    it('gives every shape the same definition for a shared field', () => {
        // The drift this guards: five hand-transcribed copies of `table_layout` could disagree about
        // its item type or its description and nothing would notice. They come from one dictionary now.
        const shapes = [
            'ContentObjectTypeItem',
            'ContentObjectType',
            'ContentObjectTypeCatalogEntry',
            'InCodeTypeDefinition',
            'CreateContentObjectTypePayload',
        ];
        for (const field of ['table_layout', 'object_schema', 'strict_mode', 'intake', 'editing', 'status']) {
            const rendered = shapes.map((shape) => JSON.stringify(property(shape, field)));
            expect(new Set(rendered).size, `${field} differs across the content-type shapes`).toBe(1);
        }
    });

    it('keeps the published property order, which composition must not reshuffle', () => {
        // Order is contract: it decides the order of the generated clients' constructor arguments and
        // model fields. The five orders differ because they were derived from five different types.
        expect(properties('ContentObjectTypeItem')).toEqual(properties('ContentObjectType'));
        expect(properties('ContentObjectTypeCatalogEntry').slice(0, 12)).toEqual(properties('InCodeTypeDefinition'));
        expect(properties('CreateContentObjectTypePayload')).toEqual([
            'status',
            'is_chunkable',
            'intake',
            'editing',
            'table_layout',
            'object_schema',
            'strict_mode',
            'name',
            'description',
            'tags',
        ]);
    });

    it('keeps the audit fields required on a stored type and optional in the catalog', () => {
        // Not a detail: a catalog entry may be an in-code type contributed by a plugin, which nobody
        // created and nobody has modified. Requiring the four there would reject a legitimate entry.
        const audit = ['updated_by', 'created_by', 'created_at', 'updated_at'];
        const required = (name: string) => (ApiSchemaComponents[name] as { required?: string[] }).required ?? [];

        expect(required('ContentObjectTypeItem')).toEqual(expect.arrayContaining(audit));
        expect(required('ContentObjectType')).toEqual(expect.arrayContaining(audit));
        for (const field of audit) {
            expect(required('ContentObjectTypeCatalogEntry')).not.toContain(field);
            expect(property('ContentObjectTypeCatalogEntry', field)).toEqual({ type: 'string' });
        }
    });

    it('accepts a catalog entry for an in-code type that has no audit trail', () => {
        expect(
            validateApiResponse('ContentObjectTypeCatalogEntry', {
                id: 'sys:Invoice',
                name: 'Invoice',
                is_chunkable: false,
            }).valid,
        ).toBe(true);
    });

    it('publishes `title` on the app-contribution shapes and withholds it from the stored ones', () => {
        // An app package contributes a display title alongside the app-local `name`, exactly as
        // `InCodeViewDefinition` and `InCodeProcessDefinition` do. Only the two shapes that carry a
        // contribution get it; a type someone stored through the API has no `title` to publish.
        for (const shape of ['InCodeTypeDefinition', 'ContentObjectTypeCatalogEntry']) {
            expect(property(shape, 'title'), `${shape} should publish title`).toBeDefined();
        }
        for (const shape of ['ContentObjectTypeItem', 'ContentObjectType', 'CreateContentObjectTypePayload']) {
            expect(property(shape, 'title'), `${shape} should not publish title`).toBeUndefined();
        }
    });

    it('accepts an app-contributed type that carries a title', () => {
        // The regression: deployed app packages send `title`, the shape was strict and did not
        // declare it, so every `GET /projects/:projectId/app-types` failed its own response contract.
        expect(
            validateApiResponse('InCodeTypeDefinition', {
                id: 'invoice',
                name: 'invoice',
                title: 'Invoice',
            }).valid,
        ).toBe(true);
    });
});
