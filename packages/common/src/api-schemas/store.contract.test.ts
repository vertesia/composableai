/** Exact type identity — `extends` in both directions is too weak (any/unknown slip through). */
type Equals<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;
function assertType<T extends true>(_ok: T): void {}

/**
 * The intake policy is now stated once, in Zod, and reaches its consumers three ways: as the
 * published OpenAPI component, as the checked-in JSON artifact that zeno-server / the workflow tool /
 * the web editor compiles, and as the TypeScript type. This file is the gate that keeps all three
 * the same statement.
 *
 * It also pins the behaviour changes the conversion makes, because the schema it replaced was
 * hand-written and disagreed with the contract in both directions. Each is asserted rather than
 * described: the whole point of the migration is that a disagreement fails a build instead of
 * shipping.
 */
const ajv = new Ajv({ strict: false, allErrors: true });
const validate = ajv.compile<ContentTypeIntakePolicy>(GeneratedIntakePolicySchema);

function errors(): string {
    return ajv.errorsText(validate.errors, { separator: '\n' });
}

/**
 * Reads a file from the studio repository this package is a submodule of.
 *
 * `undefined` when it is not there, which is the normal state in this repository's own CI: it clones
 * composableai alone, so nothing above the submodule root exists. Two of the gates below compare
 * against the published document and the generated-client fixture, both of which live up there — so
 * they are skipped when they cannot be read rather than failing the whole file at import time, which
 * is what used to happen and what left this suite red on every commit.
 *
 * They still run where they are the actual gate: a checkout of the parent repository, which is what
 * the migration's own verification and the studio CI use.
 */
function readFromStudioRepo(relativePath: string): unknown {
    try {
        return JSON.parse(readFileSync(fileURLToPath(new URL(relativePath, import.meta.url)), 'utf8'));
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
        throw error;
    }
}

const publishedDocument = readFromStudioRepo('../../../../../packages/api-specs/vertesia-openapi.json') as
    | { components: { schemas: Record<string, Record<string, unknown>> } }
    | undefined;
const published = publishedDocument?.components.schemas ?? {};

/**
 * The published component minus the OpenAPI-only discriminator hint the bundler drops.
 *
 * Written out here rather than imported from the registry on purpose: reusing the production
 * function to check the production function would make the comparison below pass by construction.
 * The rule is small enough to state twice, and stating it twice is what makes it a gate.
 */
function withoutDiscriminatorHints(value: unknown): unknown {
    if (Array.isArray(value)) return value.map(withoutDiscriminatorHints);
    if (!value || typeof value !== 'object') return value;
    const node = value as Record<string, unknown>;
    const restated = node.discriminator !== undefined && node.properties === undefined;
    return Object.fromEntries(
        Object.entries(node)
            .filter(([key]) => key !== 'discriminator' && !(restated && (key === 'type' || key === 'required')))
            .map(([key, item]) => [key, withoutDiscriminatorHints(item)]),
    );
}

function $defsOf(schema: unknown): unknown {
    return (schema as { $defs: unknown }).$defs;
}

describe.skipIf(!publishedDocument)('gate — generated artifact = canonical component = published component', () => {
    it('is the exact bundle the registry emits, so the artifact is compiled output', () => {
        // Deep equality, not a spot check: the file is generated by `pnpm run gen:schemas` from this
        // same function, so any difference means someone hand-edited it or forgot to regenerate.
        expect(GeneratedIntakePolicySchema).toEqual(bundleCanonicalComponent('ContentTypeIntakePolicy'));
    });

    it('describes the same shape as the component the OpenAPI document publishes', () => {
        // The artifact re-roots `#/components/schemas/X` to `#/$defs/X` so AJV and Monaco can compile
        // it standalone. Undoing that is what makes the two directly comparable.
        const { $defs, ...body } = GeneratedIntakePolicySchema as { $defs: Record<string, unknown> };
        const rerooted = JSON.parse(JSON.stringify(body).replaceAll('#/$defs/', '#/components/schemas/'));
        expect(rerooted).toEqual(withoutDiscriminatorHints(published.ContentTypeIntakePolicy));

        // ...and every definition it carries is the published component of that name, so the bundle
        // cannot describe a private variant of a shared type.
        for (const [name, definition] of Object.entries($defs)) {
            const asComponent = JSON.parse(JSON.stringify(definition).replaceAll('#/$defs/', '#/components/schemas/'));
            expect(asComponent, `$defs.${name} disagrees with the published component`).toEqual(
                withoutDiscriminatorHints(published[name]),
            );
        }
    });

    it('drops the discriminator hint the published component keeps, and only that', () => {
        // The one place the artifact and the component are allowed to differ, pinned from both sides
        // so neither can move alone. `synthesizeDiscriminator` restates `type` and `required` on the
        // union node for the generated Java/Go clients; the node has no `properties`, and Gemini
        // rejects the whole tool schema over it ("requires unspecified property '_option_id'") when
        // the artifact reaches Vertex inside `create_or_update_type`'s input schema.
        expect(published.ModelOptions).toMatchObject({
            discriminator: { propertyName: '_option_id' },
            type: 'object',
            required: ['_option_id'],
        });

        const bundled = ($defsOf(GeneratedIntakePolicySchema) as Record<string, Record<string, unknown>>).ModelOptions;
        expect(bundled.discriminator).toBeUndefined();
        expect(bundled.required).toBeUndefined();
        expect(bundled.type).toBeUndefined();
        // The branches are what carried the contract all along, so nothing was validated away.
        expect((bundled.oneOf as unknown[]).length).toBe(
            ((published.ModelOptions as { oneOf: unknown[] }).oneOf ?? []).length,
        );
    });

    it('registers the component the alias claims, under the id the alias name requires', () => {
        expect(Object.keys(ApiSchemaComponents)).toContain('ContentTypeIntakePolicy');
        assertType<Equals<ContentTypeIntakePolicy, (typeof ContentTypeIntakePolicySchema)['_zod']['output']>>(true);
    });
});

